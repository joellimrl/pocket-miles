import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';
import {CATEGORIES} from '../public/rules.js';

test('public detailed sheet navigates categories, recalculates scenarios and never reads or writes a wallet',async t=>{
 const dom=new JSDOM(await readFile(new URL('../public/detailed.html',import.meta.url),'utf8'),{url:'https://joellimrl.github.io/pocket-miles/detailed.html?currency=foreign#dining'});
 t.after(()=>dom.window.close());
 const {window}=dom;
 Object.defineProperty(globalThis,'document',{value:window.document,configurable:true});
 Object.defineProperty(globalThis,'window',{value:window,configurable:true});
 Object.defineProperty(globalThis,'localStorage',{get(){throw new Error('Reference must not access credentials or wallet storage');},configurable:true});
 globalThis.fetch=()=>{throw new Error('Reference must not contact the private API');};
 await import('../public/detailed.js');
 const $=id=>window.document.getElementById(id);
 const event=(id,type)=>$(id).dispatchEvent(new window.Event(type,{bubbles:true}));
 const value=(card,route)=>window.document.querySelector(`#dining [data-card=${card}] [data-route=${route}] .value`)?.textContent;
 assert.equal($('sheet-currency').value,'foreign');assert.equal($('sheet-category').value,'dining');
 assert.equal(window.document.querySelectorAll('.category-sheet').length,1);
 assert.deepEqual([...window.document.querySelectorAll('#dining .primary-comparison thead [data-route]')].map(el=>el.dataset.route),['tap','online']);
 const other=window.document.querySelector('#dining .other-methods');
 assert.equal(other.open,false);
 assert.deepEqual([...other.querySelectorAll('thead [data-route]')].map(el=>el.dataset.route),['wallet','card','insert']);
 other.open=true;
 assert.equal(value('citi','online'),'4');assert.equal(value('citi','wallet'),'0.4');
 assert.match($('sheet-results').textContent,/2.1% FX spread/);
 $('sheet-currency').value='sgd';event('sheet-currency','change');assert.equal(window.location.search,'');
 assert.equal(window.document.querySelectorAll('.primary-comparison [data-card=amaze]').length,0);
 assert.equal(window.document.querySelectorAll('.category-sheet .primary-comparison tbody tr').length,4);
 assert.doesNotMatch($('sheet-status').textContent,/\+ Amaze/);
 $('sheet-currency').value='foreign';event('sheet-currency','change');assert.equal(window.location.search,'?currency=foreign');
 assert.equal(window.document.querySelectorAll('.primary-comparison [data-card=amaze]').length,1);
 $('sheet-amount').value='12.5';event('sheet-amount','input');
 assert.equal(window.document.querySelector('#dining .other-methods').open,true);
 assert.equal(value('uob','tap'),'24');assert.equal(value('citi','online'),'48');
 assert.equal(value('citi','wallet'),'4.8');
 $('sheet-citi').value='0';event('sheet-citi','input');assert.equal(value('citi','online'),'4.8');
 $('sheet-uob').checked=false;event('sheet-uob','change');assert.equal(value('uob','tap'),'12');
 $('sheet-amount').value='-1';event('sheet-amount','input');assert.equal($('sheet-results').hidden,true);assert.equal($('sheet-error').hidden,false);
 $('sheet-amount').value='';event('sheet-amount','input');assert.equal($('sheet-results').hidden,false);
 $('sheet-category').value='marketplace';event('sheet-category','change');
 assert.equal(window.location.hash,'#marketplace');
 assert.equal(window.document.querySelectorAll('[data-route=tap]').length,0);
 $('sheet-category').value='all';event('sheet-category','change');
 assert.equal(window.document.querySelectorAll('.category-sheet').length,CATEGORIES.length);
 assert.equal(window.document.querySelectorAll('.category-sheet .primary-comparison tbody tr').length,CATEGORIES.length*5-1);
 assert.equal(window.document.querySelector('#mrt [data-card=amaze]'),null);
 $('sheet-currency').value='sgd';event('sheet-currency','change');
 assert.equal(window.document.querySelectorAll('.category-sheet .primary-comparison tbody tr').length,CATEGORIES.length*4);
 assert.equal(window.document.querySelectorAll('.primary-comparison [data-card=amaze]').length,0);
 assert.equal(window.document.querySelectorAll('th:not([scope])').length,0);
 const quick=new JSDOM(await readFile(new URL('../public/quick.html',import.meta.url),'utf8'));
 for(const link of quick.window.document.querySelectorAll('a[href*="detailed.html#"],a[href*="currency=foreign#"]'))assert.ok(CATEGORIES.some(c=>c.id===link.getAttribute('href').split('#')[1]));
 quick.window.close();
});
